import httpx
import os
import json
import re
import asyncio
from typing import Optional, Dict, Any
from apps.api.core.concurrency import governor, Priority
from apps.api.core.model_router import model_router

OLLAMA_URL = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434")
DEFAULT_TIMEOUT = float(os.getenv("OLLAMA_TIMEOUT", "120.0"))

class OllamaClient:
    def __init__(self, timeout: float = DEFAULT_TIMEOUT):
        self.timeout = httpx.Timeout(timeout, connect=5.0)
        self.router = model_router
        
    async def is_available(self) -> bool:
        try:
            async with httpx.AsyncClient(timeout=3.0) as client:
                response = await client.get(f"{OLLAMA_URL}/api/tags")
                return response.status_code == 200
        except Exception:
            return False

    async def generate(self, prompt: str, task_complexity: str = "light", structured_format: Optional[str] = None, priority: int = Priority.INTERACTIVE, max_tokens: Optional[int] = None, system: Optional[str] = None) -> Dict[str, Any]:
        # Acquire QoS lock based on priority
        await governor.acquire(priority)
        try:
            # Standalone Model Router with fallback cascade (Patch P-08)
            chosen_model = self.router.resolve_model(task_complexity)

            # Local-only / zero-egress safety check
            if "localhost" not in OLLAMA_URL and "127.0.0.1" not in OLLAMA_URL:
                 return {"success": False, "error": "Zero-egress violation: OLLAMA_BASE_URL must be local."}

            num_predict = max_tokens or (1536 if task_complexity in ("deep", "reasoning", "heavy", "complex") else 512)

            payload = {
                "model": chosen_model,
                "prompt": prompt,
                "stream": False,
                "keep_alive": -1,
                "options": {
                    "num_predict": num_predict,
                    "temperature": 0.2,
                }
            }
            if system:
                payload["system"] = system
            if structured_format:
                payload["format"] = "json"
                
            # Allow longer timeout for deep reasoning tasks on local machines
            request_timeout = self.timeout
            if task_complexity in ("deep", "reasoning", "heavy", "complex"):
                read_timeout = max(self.timeout.read or 120.0, 180.0)
                request_timeout = httpx.Timeout(read_timeout, connect=5.0)

            async with httpx.AsyncClient(timeout=request_timeout) as client:
                response = await client.post(f"{OLLAMA_URL}/api/generate", json=payload)
                response.raise_for_status()
                result = response.json()
                raw_text = result.get("response", "")
                if not raw_text or not raw_text.strip():
                    raw_text = result.get("thinking", "")
                
                if structured_format == "json":
                    try:
                        # Clean out thinking blocks and markdown fences if generated by reasoning models (e.g. Qwen3)
                        cleaned_json = re.sub(r"<(thought|think)>[\s\S]*?</\1>", "", raw_text).strip()
                        match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", cleaned_json)
                        if match:
                            cleaned_json = match.group(1).strip()
                        
                        try:
                            parsed_json = json.loads(cleaned_json)
                        except json.JSONDecodeError:
                            s = cleaned_json.find("{")
                            e = cleaned_json.rfind("}")
                            if s != -1 and e != -1 and e > s:
                                parsed_json = json.loads(cleaned_json[s:e+1])
                            else:
                                s_arr = cleaned_json.find("[")
                                e_arr = cleaned_json.rfind("]")
                                if s_arr != -1 and e_arr != -1 and e_arr > s_arr:
                                    parsed_json = json.loads(cleaned_json[s_arr:e_arr+1])
                                else:
                                    raise
                        return {"success": True, "response": parsed_json, "model_used": chosen_model}
                    except Exception:
                        return {"success": False, "error": "Invalid JSON response", "raw": raw_text, "model_used": chosen_model}
                
                # For free-form text, strip <thought> or <think> tags from clean output if present
                clean_text = re.sub(r"<(thought|think)>[\s\S]*?</\1>", "", raw_text).strip()
                if not clean_text and raw_text:
                    clean_text = raw_text.strip()

                return {"success": True, "response": clean_text, "model_used": chosen_model}
        except httpx.HTTPError as e:
            err_detail = str(e) if str(e) else e.__class__.__name__
            return {"success": False, "error": f"Local model unavailable: {err_detail}"}
        except Exception as e:
            return {"success": False, "error": str(e)}
        finally:
            await governor.release()

    def compute_embedding(self, text: str, dims: int = 64) -> list[float]:
        """
        Computes a normalized semantic embedding vector for `text`.
        Attempts local Ollama `/api/embeddings` when `TARS_USE_OLLAMA_EMBEDDINGS=true`,
        and falls back to deterministic character/word n-gram projection so offline
        and low-latency hybrid search remains fast and deterministic.
        """
        import hashlib
        import math
        clean = (text or "").strip().lower()
        if not clean:
            return [0.0] * dims

        if not hasattr(self, "_embed_cache"):
            self._embed_cache: Dict[str, list[float]] = {}
        cache_key = f"{dims}:{clean[:512]}"
        if cache_key in self._embed_cache:
            return self._embed_cache[cache_key]

        if os.getenv("TARS_USE_OLLAMA_EMBEDDINGS", "").lower() in ("1", "true", "yes"):
            embed_model = os.getenv("TARS_EMBED_MODEL", "nomic-embed-text")
            try:
                with httpx.Client(timeout=1.5) as client:
                    resp = client.post(
                        f"{self.base_url}/api/embeddings",
                        json={"model": embed_model, "prompt": clean[:1000]},
                    )
                    if resp.status_code == 200:
                        vec = resp.json().get("embedding")
                        if isinstance(vec, list) and len(vec) > 0:
                            norm = math.sqrt(sum(float(x) * float(x) for x in vec)) or 1.0
                            normed = [float(x) / norm for x in vec]
                            self._embed_cache[cache_key] = normed
                            return normed
            except Exception:
                pass

        # Deterministic character 3-gram + token projection
        vec = [0.0] * dims
        tokens = [t for t in clean.replace("-", " ").replace("_", " ").split() if len(t) >= 2]
        features = list(tokens)
        for tok in tokens:
            if len(tok) >= 4:
                features.append(tok[:4])
            for i in range(max(0, len(tok) - 2)):
                features.append(tok[i : i + 3])
        if not features:
            features = [clean]

        for feat in features:
            digest = hashlib.md5(feat.encode("utf-8")).digest()
            idx = digest[0] % dims
            sign = 1.0 if (digest[1] & 1) == 0 else -1.0
            weight = 1.5 if feat in tokens else 0.6
            vec[idx] += sign * weight

        norm = math.sqrt(sum(v * v for v in vec)) or 1.0
        normed = [round(v / norm, 6) for v in vec]
        if len(self._embed_cache) > 2048:
            self._embed_cache.clear()
        self._embed_cache[cache_key] = normed
        return normed

    def cosine_similarity(self, text_a: str, text_b: str) -> float:
        vec_a = self.compute_embedding(text_a)
        vec_b = self.compute_embedding(text_b, dims=len(vec_a))
        if not vec_a or not vec_b or len(vec_a) != len(vec_b):
            return 0.0
        dot = sum(a * b for a, b in zip(vec_a, vec_b))
        return max(0.0, min(1.0, float(dot)))

ollama_client = OllamaClient()
